"""Audit the KAIST varying-load files (current/temperature TDMS + vibration MAT).

Usage:
  .venv/Scripts/python.exe -I scripts/audit_kaist.py --root D:/bahrain-data/extracted/kaist

Writes manifests/kaist_recordings.csv and reports/data_audit_kaist.md.
Pairing evidence is assessed from metadata only (acquisition systems, rates,
absolute start/creation times). No cross-correlation or label information is
used to align the modalities.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from collections import Counter
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

from cmkd.io.kaist import canonical_stem, parse_internal_name, parse_stem, read_current_temp, read_vibration, to_datetime

ROOT = Path(__file__).resolve().parents[1]
CLASS3 = {"Normal": "healthy", "BPFI": "inner", "BPFO": "outer"}


def audit_pair(args: tuple[str, str | None, str | None]) -> dict:
    stem, vib_path, cur_path = args
    p = parse_stem(stem)
    row = {"stem": stem, **p, "class": CLASS3.get(p["condition"], p["condition"].lower())}
    if vib_path:
        b = Path(vib_path).read_bytes()
        row["vib_file"] = Path(vib_path).name
        row["vib_sha256"] = hashlib.sha256(b).hexdigest()
        v = read_vibration(vib_path)
        vals = v.pop("values")
        row.update(
            vib_fs=v["fs"], vib_n=v["n"], vib_rows=vals.shape[0], vib_cols=vals.shape[1],
            vib_duration_s=v["n"] / v["fs"], vib_start_value=v["start_value"], vib_unit=v["unit"],
            vib_channels="|".join(v["channel_names"]), vib_creation_time=v["creation_time"],
            vib_exporter=v["exporter"], vib_nonfinite=int((~np.isfinite(vals)).sum()),
            vib_std="|".join(f"{s:.4g}" for s in vals.std(0)),
        )
    if cur_path:
        b = Path(cur_path).read_bytes()
        row["cur_file"] = Path(cur_path).name
        row["cur_sha256"] = hashlib.sha256(b).hexdigest()
        c = read_current_temp(cur_path)
        row.update(internal_name=c["internal_name"], run_number=c["run_number"], tdms_created=c["date_created"], product=c["product"])
        ip = parse_internal_name(c["internal_name"])
        row.update(internal_load=ip["load_nm"], internal_condition=ip["condition"], internal_severity=ip["severity"])
        cur_channels = {k: e for k, e in c["channels"].items() if e["type"] == "Current"}
        nonempty = {k: e for k, e in cur_channels.items() if e.get("n", 0) > 0}
        row["current_channels_nonempty"] = "|".join(sorted(nonempty))
        row["current_channels_empty"] = "|".join(sorted(set(cur_channels) - set(nonempty)))
        first = next(iter(nonempty.values()), None)
        if first is not None:
            row.update(
                cur_fs=1.0 / float(first["wf_increment"]), cur_n=first["n"],
                cur_duration_s=first["n"] * float(first["wf_increment"]),
                cur_start_time=first["wf_start_time"], cur_device=first["device"], cur_chassis=first["chassis"],
                cur_std="|".join(f"{np.std(e['values']):.4g}" for e in nonempty.values()),
            )
    # metadata-only time comparison; vibration creation time is local wall-clock
    # (time zone not stated), TDMS start time is stored by FlexLogger (UTC assumed)
    vt, ct = to_datetime(row.get("vib_creation_time", "")), to_datetime(row.get("cur_start_time", ""))
    if vt and ct:
        row["vib_minus_cur_minutes_raw"] = (vt - ct).total_seconds() / 60.0
        row["vib_minus_cur_minutes_if_KST"] = row["vib_minus_cur_minutes_raw"] - 9 * 60.0
    return row


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--workers", type=int, default=8)
    args = ap.parse_args()
    vib = {canonical_stem(p.stem): str(p) for p in (args.root / "vibration").glob("*.mat")}
    cur = {canonical_stem(p.stem): str(p) for p in (args.root / "current_temp").glob("*.tdms")}
    stems = sorted(set(vib) | set(cur))
    with ProcessPoolExecutor(max_workers=args.workers) as ex:
        rows = list(ex.map(audit_pair, [(s, vib.get(s), cur.get(s)) for s in stems]))
    df = pd.DataFrame(rows).sort_values(["condition", "severity", "load_nm"]).reset_index(drop=True)
    df["dataset"] = "kaist_varying_load_v6"
    df["severity_name_consistent"] = df.apply(
        lambda r: (str(r.get("internal_severity", "")).lower().replace("mm", "").lstrip("0") == str(r["severity"]).lstrip("0"))
        if r["condition"] in ("BPFI", "BPFO") else None, axis=1)
    df.to_csv(ROOT / "manifests/kaist_recordings.csv", index=False)

    L = ["# KAIST varying-load audit (generated by scripts/audit_kaist.py)", ""]
    L += [f"File stems: {len(stems)}; vibration files: {len(vib)}; current/temperature files: {len(cur)}.", ""]
    L += ["## Bearing-relevant recordings (healthy / inner / outer)", ""]
    cols = ["stem", "class", "load_nm", "severity", "internal_name", "run_number", "current_channels_nonempty", "current_channels_empty",
            "cur_fs", "cur_duration_s", "vib_fs", "vib_duration_s", "cur_start_time", "vib_creation_time", "vib_minus_cur_minutes_if_KST"]
    sub = df[df["class"].isin(["healthy", "inner", "outer"])]
    L += [sub[cols].round(3).to_markdown(index=False), ""]
    L += ["## Other conditions (misalignment / unbalance)", ""]
    L += [df[~df["class"].isin(["healthy", "inner", "outer"])][cols].round(3).to_markdown(index=False), ""]
    L += ["## Summary checks", ""]
    L += [f"- vibration sampling rates: {dict(Counter(np.round(df['vib_fs'].dropna(), 3)))}",
          f"- current sampling rates: {dict(Counter(np.round(df['cur_fs'].dropna(), 3)))}",
          f"- vibration durations (s): {dict(Counter(np.round(df['vib_duration_s'].dropna(), 3)))}",
          f"- current durations (s): {dict(Counter(np.round(df['cur_duration_s'].dropna(), 3)))}",
          f"- current channel sets: {dict(Counter(df['current_channels_nonempty'].fillna('')))}",
          f"- non-finite vibration samples: {int(df['vib_nonfinite'].fillna(0).sum())}",
          f"- internal severity inconsistent with file name: {df.loc[df['severity_name_consistent'] == False, 'stem'].tolist()}",
          f"- vibration-minus-current start offset if vibration time is KST (minutes): min {df['vib_minus_cur_minutes_if_KST'].min():.2f}, median {df['vib_minus_cur_minutes_if_KST'].median():.2f}, max {df['vib_minus_cur_minutes_if_KST'].max():.2f}",
          ""]
    (ROOT / "reports/data_audit_kaist.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[-10:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())

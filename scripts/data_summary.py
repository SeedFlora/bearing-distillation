"""Generate reports/data_summary.md and paper table data from manifests only.

Usage: .venv/Scripts/python.exe -I scripts/data_summary.py

Separates independent units (physical bearings) from raw recordings and from
derived windows, per split, so the paper never presents windows as samples of
independent specimens.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CACHE_INDEX = Path("D:/bahrain-data/cache/paderborn/v2/index.csv")
WIN_S, STRIDE_TRAIN_S, RATE = 0.5, 0.25, 8000


def n_windows(valid: pd.Series, win: int, stride: int) -> int:
    v = valid[valid >= win]
    return int(((v - win) // stride + 1).sum())


def main() -> int:
    pop = pd.read_csv(ROOT / "manifests/splits/paderborn_population.csv")
    rec = pd.read_csv(ROOT / "manifests/paderborn_recordings.csv")
    idx = pd.read_csv(CACHE_INDEX) if CACHE_INDEX.exists() else None
    A = json.loads((ROOT / "manifests/splits/protocol_A.json").read_text())
    dev = json.loads((ROOT / "manifests/splits/dev_pool.json").read_text())["bearings"]
    win, stride = int(WIN_S * RATE), int(STRIDE_TRAIN_S * RATE)

    L = ["# Data summary (generated by scripts/data_summary.py)", ""]
    prim = pop[pop["in_primary"]]
    L += ["## Independent units: physical bearings in the primary three-class population", ""]
    L += [pd.crosstab(prim["class3"], prim["damage_origin"], margins=True).to_markdown(), ""]
    kept = rec[(rec["exclude_reason"].fillna("") == "") & rec["bearing"].isin(prim["bearing"])]
    L += ["## Raw recordings (4 s each) retained in the primary population", ""]
    L += [pd.crosstab(kept["bearing"].map(dict(zip(pop["bearing"], pop["class3"]))).rename("class"), kept["condition"], margins=True).to_markdown(), ""]
    if idx is not None:
        ip = idx[idx["bearing"].isin(prim["bearing"])]
        rows = []
        for f in A["folds"]:
            for part in ("train", "validation", "test"):
                sub = ip[ip["bearing"].isin(f[part])]
                rows.append({"fold": f["fold"], "partition": part, "bearings": len(f[part]), "recordings": len(sub),
                             "eval_windows (0.5 s, no overlap)": n_windows(sub["valid_current_8000"], win, win),
                             "train_windows (stride 0.25 s)": n_windows(sub["valid_current_8000"], win, stride) if part == "train" else None})
        L += ["## Derived windows per Protocol A partition (8-kHz current; windows are not independent units)", ""]
        L += [pd.DataFrame(rows).to_markdown(index=False), ""]
        d = ip[ip["bearing"].isin(dev)]
        L += [f"Development pool ({', '.join(dev)}): {len(dev)} bearings, {len(d)} recordings, "
              f"{n_windows(d['valid_current_8000'], win, win)} non-overlapping windows; never used as test evidence.", ""]
    (ROOT / "reports/data_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
